"""Offline public Wisconsin research model serving and aggregate-only monitoring.

No patient records, personal identifiers, persistent logs, diagnosis, or clinical
risk claims. Load ONLY artifacts generated by this trusted repository's training.
Unsafe pickle/joblib files from arbitrary users MUST never be deserialized.
"""
from __future__ import annotations

from functools import lru_cache
from hashlib import sha256
import json
import os
from pathlib import Path
from threading import Lock

import joblib
import numpy as np
import pandas as pd
from fastapi import FastAPI, HTTPException
from pydantic import BaseModel, Field
from sklearn.datasets import load_breast_cancer


class Batch(BaseModel):
    records: list[dict[str, float]] = Field(min_length=1, max_length=128)


class ServingModel:
    def __init__(self, run_dir: str | Path):
        self.path = Path(run_dir)
        self.meta_path = self.path / "train_meta.json"
        self.meta = json.loads(self.meta_path.read_text(encoding="utf-8"))
        if (self.meta.get("data_source") != "sklearn Wisconsin Breast Cancer"
                or self.meta.get("positive_label") != 1
                or self.meta.get("positive_outcome") != "malignant"
                or self.meta.get("n_features") != 30):
            raise ValueError("Refusing unknown model/data/class-label contract")
        self.feature_names = list(load_breast_cancer(as_frame=True).feature_names)
        self.selected = max(
            self.meta["models"],
            key=lambda name: self.meta["cv_results"][name]["cv_auroc_mean"],
        )
        model_path = self.path / ("model_" + self.selected + ".joblib")
        self.model_sha256 = sha256(model_path.read_bytes()).hexdigest()
        self.model = joblib.load(model_path)  # trust LOCAL training artifacts only
        if (list(getattr(self.model, "classes_", [])) != [0, 1] or
                list(getattr(self.model, "feature_names_in_", [])) != self.feature_names):
            raise ValueError("Model class or feature contract disagrees with original source")
        self.reference = json.loads(
            (self.path / "monitoring_reference.json").read_text(encoding="utf-8"))
        if self.reference.get("features") != self.feature_names:
            raise ValueError("Reference feature schema disagrees with fitted model")
        self.lock = Lock()
        self.requests = 0
        self.observations = 0
        self.positive_sum = 0.0
        self.outside_cells = 0
        self.total_cells = 0
        self.probability_bins = [0, 0, 0, 0, 0]

    def predict(self, records):
        if not 1 <= len(records) <= 128:
            raise ValueError("Batch must have between 1 and 128 research records")
        expected = set(self.feature_names)
        for i, row in enumerate(records):
            if set(row) != expected:
                raise ValueError(
                    f"Record {i} must provide exactly the 30 original feature names")
        values = np.array([[row[c] for c in self.feature_names] for row in records], dtype=float)
        if not np.isfinite(values).all():
            raise ValueError("All source measurements must be finite")
        frame = pd.DataFrame(values, columns=self.feature_names)
        probs = np.asarray(self.model.predict_proba(frame), dtype=float)[:, 1]
        if (probs.shape != (len(records),) or not np.isfinite(probs).all() or
                np.any((probs < 0) | (probs > 1))):
            raise ValueError("Model returned invalid malignant-class scores")
        lows = np.array([self.reference["lower_training_percentile_01"][c]
                         for c in self.feature_names])
        highs = np.array([self.reference["upper_training_percentile_99"][c]
                          for c in self.feature_names])
        out = int(((values < lows) | (values > highs)).sum())
        hist, _ = np.histogram(probs, bins=[0, .2, .4, .6, .8, 1.00001])
        with self.lock:
            self.requests += 1
            self.observations += len(records)
            self.positive_sum += float(probs.sum())
            self.outside_cells += out
            self.total_cells += int(values.size)
            self.probability_bins = [int(a+b) for a, b in zip(self.probability_bins, hist)]
        return {
            "model": self.selected,
            "model_sha256": self.model_sha256,
            "malignant_positive_label": 1,
            "research_probability_malignant": [float(x) for x in probs],
            "research_only": True,
            "clinical_decision_support": False,
            "warning": "Historic public Wisconsin data; not a diagnosis or validated patient risk.",
        }

    def metrics(self):
        with self.lock:
            n = self.observations
            return {
                "model": self.selected, "model_sha256": self.model_sha256,
                "requests": self.requests, "observations": n,
                "mean_probability_malignant": (self.positive_sum/n if n else None),
                "probability_bins_0_20_40_60_80_100": list(self.probability_bins),
                "feature_cells_outside_training_1st_99th_percentile": self.outside_cells,
                "feature_cells_evaluated": self.total_cells,
                "outside_training_envelope_fraction":
                    (self.outside_cells/self.total_cells if self.total_cells else None),
                "reference_rows": self.reference["n_training_rows"],
                "monitoring_excludes_raw_records": True,
                "drift_alert_is_not_clinical_validation": True,
                "state": "in-memory aggregate only; resets on process restart",
            }


@lru_cache(maxsize=1)
def get_serving_model():
    return ServingModel(os.environ.get("HC_RUN_DIR", "runs/ci_demo"))


app = FastAPI(
    title="Wisconsin Research ML Inference",
    version="0.1.0",
    description="Locally fitted historic public dataset model. Never clinical decision support.",
)


@app.get("/health")
def health():
    try:
        m = get_serving_model()
        return {"status": "ok", "model": m.selected, "model_sha256": m.model_sha256,
                "historic_public_dataset_only": True, "clinical_decision_support": False}
    except (OSError, KeyError, ValueError) as exc:
        raise HTTPException(status_code=503, detail="Trusted trained research artifact missing or invalid") from exc


@app.get("/schema")
def schema():
    try:
        m = get_serving_model()
        return {"features_in_order": m.feature_names, "positive_label": 1,
                "positive_outcome": "malignant",
                "public_research_data_only": True}
    except (OSError, KeyError, ValueError) as exc:
        raise HTTPException(status_code=503, detail="Trained research model unavailable") from exc


@app.post("/predict")
def predict(batch: Batch):
    try:
        return get_serving_model().predict(batch.records)
    except (ValueError, TypeError) as exc:
        raise HTTPException(status_code=422, detail=str(exc)) from exc
    except (OSError, KeyError) as exc:
        raise HTTPException(status_code=503, detail="Trained research model unavailable") from exc


@app.get("/metrics")
def metrics():
    try:
        return get_serving_model().metrics()
    except (OSError, KeyError, ValueError) as exc:
        raise HTTPException(status_code=503, detail="Trained research model unavailable") from exc
